-- 代理店へ渡す「返金された」を積む（`UD-1003` の手前・2026-08-22）
--
-- ⚠️ **いま送る先は無い。** 行が溜まるだけである。それでも起きた時点で
--    積む——あとから `refunds` を読めば「いつ返金になったか」は組み直せる
--    が、**そのとき積むはずだった出来事**は作り直せない。`order.paid` と
--    対に揃えておく。
--
-- ⚠️ **代理店の受け口の契約は未確定である**（`UD-1008` は
--    `common-users/resolve` までしか定めていない）。送信側は作らない。
--    こちらで契約を発明すると、あとで作り直しになる。

/*
  ⚠️ **同じ注文で 2 件積ませない。** 積めると、受け取る側が売上を
     2 回取り消す。部分 UNIQUE 索引で止める。

  ⚠️ **`order.paid` には掛けない。** あちらは既存の行があり、
     いま制約を足すと過去のデータ次第で移行が落ちる。返金は
     これから積むぶんだけなので、ここで閉じられる。

  ⚠️ Prisma では条件付き索引を書けないため、**ここにだけ存在する**。
*/
CREATE UNIQUE INDEX "outbox_events_order_refunded_once"
  ON "outbox_events" ("aggregate_id")
  WHERE "event_name" = 'order.refunded';
