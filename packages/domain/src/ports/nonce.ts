/**
 * 署名の使い捨て値（nonce）の記録。
 *
 * ⚠️ **同じ nonce を 2 回受け付けない。**
 * 署名付きの要求をそのまま録画・再送されると、正しい署名のまま
 * 同じ操作がもう一度実行される（リプレイ攻撃）。
 * 署名の検証だけでは防げない。**一度使った nonce を覚えておく**必要がある。
 *
 * ⚠️ **「探してから書く」ではなく「先に記録する」。**
 * 探す → 無い → 受け付ける、の順だと、同時に届いた 2 本が
 * 両方とも「無い」を見て両方通る。冪等キーと同じ理屈で、
 * 一意制約そのものを判定に使う。
 *
 * ⚠️ **プロセス内メモリに置かない。**
 * 台数を増やした瞬間に効かなくなり、しかもその事実が外からは見えない。
 */
export interface NonceStorePort {
  /**
   * nonce を記録する。
   *
   * @returns 初めての nonce なら `true`。既に使われていれば `false`。
   */
  remember(input: {
    readonly keyId: string;
    readonly nonce: string;
    /** この時刻を過ぎたら掃除してよい。通常は許容時間の少し先。 */
    readonly expiresAt: Date;
    /** 期限切れ判定に使う「いま」。実装が自分で時計を読まない。 */
    readonly now: Date;
  }): Promise<boolean>;
}
