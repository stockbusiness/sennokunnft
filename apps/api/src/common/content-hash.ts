/**
 * 内容ハッシュ（`sha256:<hex>`）の計算。実装は `@sengoku/integrations` の `contentHash`。
 *
 * ⚠️ **画像と配送本文で同じ関数を使う。**
 * 別々に用意すると、片方だけ形式や前置きが変わったときに
 * 「保存はできるのに照合が通らない値」ができる。
 *
 * ⚠️ **ファイル名や保存キーからではなく、中身から計算する。**
 * キーから導出すると、同じキーに別の画像を上書きしたときに
 * ハッシュが変わらず、差し替えを検出できない。
 */
export type ContentHasher = (data: string | Uint8Array) => string;
